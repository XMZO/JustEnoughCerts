package store

import (
	"bytes"
	"io"
	"io/fs"
	"regexp"
	"strings"
	"time"
)

// The migrations are written for SQLite. PostgreSQL takes them translated
// (pgSchema), but for those that come with a version of their own beside
// them, named like 00001_name.pg.sql, which SQLite does without.

const pgSuffix = ".pg.sql"

var (
	tableOptions = regexp.MustCompile(`\)\s*(?:STRICT|WITHOUT ROWID)(?:\s*,\s*(?:STRICT|WITHOUT ROWID))*\s*;`)
	rowID        = regexp.MustCompile(`\bINTEGER PRIMARY KEY(?: AUTOINCREMENT)?\b`)
	integer      = regexp.MustCompile(`\bINTEGER\b`)
	blob         = regexp.MustCompile(`\bBLOB\b`)
	reference    = regexp.MustCompile(`\bREFERENCES\s+\w+\s*\([^)]*\)(?:\s+ON\s+DELETE\s+(?:CASCADE|SET NULL|SET DEFAULT|RESTRICT|NO ACTION))?`)
)

// pgSchema translates a migration written for SQLite for PostgreSQL:
// tables lose STRICT and WITHOUT ROWID; a rowid key becomes an identity,
// INTEGER a 64-bit BIGINT, BLOB BYTEA; and foreign keys may be deferred,
// for a copy to fill tables in any order (Copy).
func pgSchema(sql string) string {
	sql = tableOptions.ReplaceAllString(sql, ");")
	sql = rowID.ReplaceAllString(sql, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
	sql = integer.ReplaceAllString(sql, "BIGINT")
	sql = blob.ReplaceAllString(sql, "BYTEA")
	return reference.ReplaceAllString(sql, "$0 DEFERRABLE INITIALLY IMMEDIATE")
}

// pgMigrations is fsys as PostgreSQL takes it: each migration translated,
// or its own version for PostgreSQL in its place.
func pgMigrations(fsys fs.FS) fs.FS { return migrationFS{base: fsys, postgres: true} }

// sqliteMigrations is fsys without the versions for PostgreSQL.
func sqliteMigrations(fsys fs.FS) fs.FS { return migrationFS{base: fsys} }

type migrationFS struct {
	base     fs.FS
	postgres bool
}

func (m migrationFS) ReadDir(name string) ([]fs.DirEntry, error) {
	entries, err := fs.ReadDir(m.base, name)
	if err != nil {
		return nil, err
	}
	own := map[string]bool{} // versions with a file for PostgreSQL
	for _, e := range entries {
		if v, ok := strings.CutSuffix(e.Name(), pgSuffix); ok {
			own[version(v)] = true
		}
	}
	var out []fs.DirEntry
	for _, e := range entries {
		pg := strings.HasSuffix(e.Name(), pgSuffix)
		switch {
		case pg && !m.postgres, !pg && m.postgres && own[version(e.Name())]:
			continue
		}
		out = append(out, e)
	}
	return out, nil
}

func (m migrationFS) Open(name string) (fs.File, error) {
	f, err := m.base.Open(name)
	if err != nil || !m.postgres || !strings.HasSuffix(name, ".sql") || strings.HasSuffix(name, pgSuffix) {
		return f, err
	}
	defer func() { _ = f.Close() }()
	data, err := io.ReadAll(f)
	if err != nil {
		return nil, err
	}
	info, err := f.Stat()
	if err != nil {
		return nil, err
	}
	return &memFile{Reader: bytes.NewReader([]byte(pgSchema(string(data)))), info: info}, nil
}

// version is the number a migration's name starts with.
func version(name string) string {
	v, _, _ := strings.Cut(name, "_")
	return v
}

// memFile is a translated migration.
type memFile struct {
	*bytes.Reader
	info fs.FileInfo
}

func (f *memFile) Stat() (fs.FileInfo, error) { return sizedInfo{f.info, f.Size()}, nil }
func (*memFile) Close() error                 { return nil }

type sizedInfo struct {
	fs.FileInfo
	size int64
}

func (i sizedInfo) Size() int64        { return i.size }
func (i sizedInfo) ModTime() time.Time { return i.FileInfo.ModTime() }
