func TestRebind(t *testing.T) {
	positional := func(vs ...any) []driver.NamedValue {
		out := make([]driver.NamedValue, len(vs))
		for i, v := range vs {
			out[i] = driver.NamedValue{Ordinal: i + 1, Value: v}
		}
		return out
	}
	for _, c := range []struct {
		query string
		args  []driver.NamedValue
		want  string
		vals  []any
	}{
		{"SELECT a FROM t WHERE b = ? AND c = ?", positional("x", int64(2)), "SELECT a FROM t WHERE b = $1 AND c = $2", []any{"x", int64(2)}},
		// Literals, quoted names, comments and casts stay; bools are 1 or 0.
		{`SELECT '?', "a?" FROM t -- ?` + "\n" + `WHERE x::text = ? /* ? */ AND y = ?`, positional(true, false),
			`SELECT '?', "a?" FROM t -- ?` + "\n" + `WHERE x::text = $1 /* ? */ AND y = $2`, []any{int64(1), int64(0)}},
		{"SELECT 'it''s ?' WHERE a = ?", positional("x"), "SELECT 'it''s ?' WHERE a = $1", []any{"x"}},
		// A name used twice keeps its number.
		{"WHERE (:a = '' OR b = :a) AND c > :since LIMIT ?", []driver.NamedValue{{Name: "a", Value: "q"}, {Name: "since", Value: int64(5)}, {Ordinal: 3, Value: int64(9)}},
			"WHERE ($1 = '' OR b = $1) AND c > $2 LIMIT $3", []any{"q", int64(5), int64(9)}},
		// LIKE ignores case, as SQLite's does; a word holding it stays.
		{"WHERE name LIKE ? AND unlike = 1 AND x NOT like ?", positional("%a%", "b"), "WHERE name ILIKE $1 AND unlike = 1 AND x NOT ILIKE $2", []any{"%a%", "b"}},
		// Numbered already, as goose's own: as it is, bools and all.
		{"INSERT INTO m (v, ok) VALUES ($1, $2)", positional(int64(1), true), "INSERT INTO m (v, ok) VALUES ($1, $2)", []any{int64(1), true}},
	} {
		got, args, err := rebind(c.query, c.args)
		if err != nil || got != c.want {
			t.Errorf("rebind(%q) = %q, %v; want %q", c.query, got, err, c.want)
			continue
		}
		var vals []any
		for i, a := range args {
			if a.Ordinal != i+1 || a.Name != "" {
				t.Errorf("%q: argument %d is %+v", c.query, i, a)
			}
			vals = append(vals, a.Value)
		}
		if !reflect.DeepEqual(vals, c.vals) {
			t.Errorf("%q: arguments %v, want %v", c.query, vals, c.vals)
		}
	}
	if _, _, err := rebind("a = ? AND b = ?", positional(1)); err == nil {
		t.Error("too few arguments passed")
	}
	if _, _, err := rebind("a = ?", positional(1, 2)); err == nil {
		t.Error("too many arguments passed")
	}
}

func TestPgSchema(t *testing.T) {
	in := `CREATE TABLE a (
    id    INTEGER PRIMARY KEY AUTOINCREMENT,
    other INTEGER NOT NULL REFERENCES b (id) ON DELETE CASCADE,
    data  BLOB,
    n     INTEGER
) STRICT, WITHOUT ROWID;
ALTER TABLE a ADD COLUMN c INTEGER REFERENCES c (id);`
	want := `CREATE TABLE a (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    other BIGINT NOT NULL REFERENCES b (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    data  BYTEA,
    n     BIGINT
);
ALTER TABLE a ADD COLUMN c BIGINT REFERENCES c (id) DEFERRABLE INITIALLY IMMEDIATE;`
	if got := pgSchema(in); got != want {
		t.Errorf("pgSchema:\n%s\nwant:\n%s", got, want)
	}
	if strings.Contains(pgSchema("CREATE TABLE x (id INTEGER PRIMARY KEY) STRICT;"), "STRICT") {
		t.Error("STRICT stays")
	}
}
