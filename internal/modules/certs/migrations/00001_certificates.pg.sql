-- 00001_certificates.sql for PostgreSQL, where a table can only refer to
-- one there already: the reference of a certificate to its current
-- version comes once both tables are.
CREATE TABLE certs_certificates (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domains            TEXT NOT NULL,
    source             TEXT NOT NULL,
    key_type           TEXT NOT NULL,
    renew_before_days  BIGINT NOT NULL,
    current_version_id BIGINT,
    created_at         BIGINT NOT NULL,
    updated_at         BIGINT NOT NULL
);

CREATE TABLE certs_versions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_id BIGINT NOT NULL REFERENCES certs_certificates (id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    origin         TEXT NOT NULL,
    names          TEXT NOT NULL,
    serial         TEXT NOT NULL,
    fingerprint    TEXT NOT NULL UNIQUE,
    issuer         TEXT NOT NULL,
    key_type       TEXT NOT NULL,
    not_before     BIGINT NOT NULL,
    not_after      BIGINT NOT NULL,
    chain          TEXT NOT NULL,
    sealed_key     BYTEA NOT NULL,
    notified       TEXT NOT NULL,
    created_at     BIGINT NOT NULL
);

ALTER TABLE certs_certificates ADD FOREIGN KEY (current_version_id)
    REFERENCES certs_versions (id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE;

CREATE INDEX certs_versions_certificate ON certs_versions (certificate_id, created_at);

