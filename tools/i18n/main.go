// Command i18n generates the message key constants and runs the i18n gates
// of PLAN.md 7.4 that do not need type information (i18nlint does the rest).
//
//	go run ./tools/i18n gen     write i18n/keys_gen.go from the base locale
//	go run ./tools/i18n fix     rewrite the locale files in canonical form, then gen
//	go run ./tools/i18n check   run the gates; exit 1 on any problem
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"golang.org/x/text/language"

	"github.com/XMZO/JustEnoughCerts/i18n"
)

// requiredLocales must translate every key of the base locale.
var requiredLocales = []language.Tag{i18n.BaseLocale, language.MustParse("zh-CN")}

// placeholder starts the texts that tools/new-module writes for a new
// module; check refuses them until someone writes the real ones.
const placeholder = "TODO:"

func main() {
	root := flag.String("root", ".", "repository root")
	flag.Usage = func() {
		fmt.Fprint(flag.CommandLine.Output(), "usage: go run ./tools/i18n [-root dir] gen|fix|check\n")
	}
	flag.Parse()
	if flag.NArg() != 1 {
		flag.Usage()
		os.Exit(2)
	}
	var err error
	switch flag.Arg(0) {
	case "gen":
		err = gen(*root)
	case "fix":
		err = fix(*root)
	case "check":
		err = check(*root)
	default:
		flag.Usage()
		os.Exit(2)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "i18n:", err)
		os.Exit(1)
	}
}

func localesDir(root string) string { return filepath.Join(root, "i18n", "locales") }
func keysFile(root string) string   { return filepath.Join(root, "i18n", "keys_gen.go") }

func readLocales(root string) ([]*i18n.File, *i18n.File, error) {
	files, err := i18n.ReadDir(os.DirFS(localesDir(root)))
	if err != nil {
		return nil, nil, err
	}
	for _, f := range files {
		if f.Tag == i18n.BaseLocale {
			return files, f, nil
		}
	}
	return nil, nil, fmt.Errorf("the base locale %s.json is missing", i18n.BaseLocale)
}

func webFile(root string) string {
	return filepath.Join(root, "web", "src", "i18n", "generated.ts")
}

func gen(root string) error {
	files, base, err := readLocales(root)
	if err != nil {
		return err
	}
	src, err := keysSource(base)
	if err != nil {
		return err
	}
	if err := os.WriteFile(keysFile(root), src, 0o644); err != nil { //nolint:gosec // G306: a source file
		return err
	}
	if err := os.MkdirAll(filepath.Dir(webFile(root)), 0o755); err != nil { //nolint:gosec // G301: a source directory
		return err
	}
	return os.WriteFile(webFile(root), tsSource(files, base), 0o644) //nolint:gosec // G306: a source file
}

// tsSource renders web/src/i18n/generated.ts: the locales for the language
// picker and the type of every message key. Names are escaped to ASCII so
// that the file passes the CJK check.
func tsSource(files []*i18n.File, base *i18n.File) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by \"go run ./tools/i18n gen\"; DO NOT EDIT.\n\n")
	b.WriteString("/** The locale files, the base locale first. */\nexport const locales = [\n")
	sorted := slices.Clone(files)
	slices.SortFunc(sorted, func(x, y *i18n.File) int {
		switch {
		case x == base:
			return -1
		case y == base:
			return 1
		}
		return strings.Compare(x.Tag.String(), y.Tag.String())
	})
	for _, f := range sorted {
		fmt.Fprintf(&b, "  { tag: %s, name: %s, dir: %s, completeness: %d },\n",
			strconv.QuoteToASCII(f.Tag.String()), strconv.QuoteToASCII(f.Meta.Name), strconv.QuoteToASCII(f.Meta.Dir), completeness(f, base))
	}
	b.WriteString("] as const\n\nexport type Locale = (typeof locales)[number]['tag']\n\n")
	fmt.Fprintf(&b, "export const baseLocale: Locale = %s\n\n", strconv.QuoteToASCII(base.Tag.String()))
	b.WriteString("/** Every message key, from the base locale. */\nexport type MessageKey =")
	keys := sortedKeys(base.Messages)
	if len(keys) == 0 {
		b.WriteString(" never\n")
		return b.Bytes()
	}
	b.WriteString("\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "  | %s\n", strconv.QuoteToASCII(string(k)))
	}
	return b.Bytes()
}

// keysSource renders keys_gen.go: one constant per key of the base locale.
func keysSource(base *i18n.File) ([]byte, error) {
	keys := sortedKeys(base.Messages)
	var b bytes.Buffer
	b.WriteString("// Code generated by \"go run ./tools/i18n gen\"; DO NOT EDIT.\n\npackage i18n\n")
	if len(keys) > 0 {
		fmt.Fprintf(&b, "\n// Message keys, from locales/%s.json.\nconst (\n", i18n.BaseLocale)
		names := map[string]i18n.Key{}
		for _, k := range keys {
			name := constName(k)
			if other, dup := names[name]; dup {
				return nil, fmt.Errorf("keys %s and %s both become the constant %s", other, k, name)
			}
			names[name] = k
			fmt.Fprintf(&b, "\t%s Key = %q\n", name, k)
		}
		b.WriteString(")\n")
	}
	return format.Source(b.Bytes())
}

// constName turns "certs.list.empty_state" into "CertsListEmptyState".
func constName(k i18n.Key) string {
	var b strings.Builder
	for _, seg := range strings.Split(string(k), ".") {
		for _, word := range strings.Split(seg, "_") {
			if word != "" {
				b.WriteString(strings.ToUpper(word[:1]) + word[1:])
			}
		}
	}
	return b.String()
}

func sortedKeys[V any](m map[i18n.Key]V) []i18n.Key {
	keys := make([]i18n.Key, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}

// completeness is the share of base keys that f translates, in percent.
func completeness(f, base *i18n.File) int {
	if f == base || len(base.Messages) == 0 {
		return 100
	}
	n := 0
	for k := range base.Messages {
		if _, ok := f.Messages[k]; ok {
			n++
		}
	}
	return n * 100 / len(base.Messages)
}

func canonical(f, base *i18n.File) ([]byte, error) {
	c := *f
	c.Meta.Completeness = completeness(f, base)
	return c.Encode()
}

func fix(root string) error {
	files, base, err := readLocales(root)
	if err != nil {
		return err
	}
	for _, f := range files {
		data, err := canonical(f, base)
		if err != nil {
			return fmt.Errorf("%s: %w", f.Tag, err)
		}
		path := filepath.Join(localesDir(root), f.Tag.String()+".json")
		if old, err := os.ReadFile(path); err == nil && sameText(old, data) {
			continue
		}
		if err := os.WriteFile(path, data, 0o644); err != nil { //nolint:gosec // G306: a source file
			return err
		}
	}
	return gen(root)
}

// sameText compares files ignoring CRLF line endings, which a Windows
// checkout may have.
func sameText(a, b []byte) bool {
	return bytes.Equal(bytes.ReplaceAll(a, []byte("\r\n"), []byte("\n")), bytes.ReplaceAll(b, []byte("\r\n"), []byte("\n")))
}

func check(root string) error { return runChecks(root).err() }

func runChecks(root string) problems {
	var p problems
	files, err := i18n.ReadDir(os.DirFS(localesDir(root)))
	if err != nil {
		p.add("%v", err)
	}
	var base *i18n.File
	for _, f := range files {
		if f.Tag == i18n.BaseLocale {
			base = f
		}
	}
	if base == nil {
		p.add("the base locale %s.json is missing or unreadable", i18n.BaseLocale)
		return p
	}
	for _, tag := range requiredLocales {
		if !slices.ContainsFunc(files, func(f *i18n.File) bool { return f.Tag == tag }) {
			p.add("%s.json is required", tag)
		}
	}
	for _, k := range sortedKeys(base.Messages) {
		if err := validKey(k); err != nil {
			p.add("%s: %v", k, err)
		}
	}
	for _, f := range files {
		checkFile(&p, root, f, base)
	}

	if src, err := keysSource(base); err != nil {
		p.add("%v", err)
	} else if old, err := os.ReadFile(keysFile(root)); err != nil || !sameText(old, src) {
		p.add("i18n/keys_gen.go is stale: run go generate ./i18n")
	}
	if old, err := os.ReadFile(webFile(root)); err != nil || !sameText(old, tsSource(files, base)) {
		p.add("web/src/i18n/generated.ts is stale: run go generate ./i18n")
	}

	used, err := usedKeyConstants(root)
	if err != nil {
		p.add("scanning Go code: %v", err)
	}
	usedWeb, err := usedWebKeys(root)
	if err != nil {
		p.add("scanning the web UI: %v", err)
	}
	for _, k := range sortedKeys(base.Messages) {
		if !used[constName(k)] && !usedWeb[k] {
			p.add("%s is not used by any code: remove it from every locale file", k)
		}
	}

	if err := scanCJK(root, &p); err != nil {
		p.add("scanning for CJK text: %v", err)
	}
	slices.Sort(p)
	return p
}

func checkFile(p *problems, root string, f, base *i18n.File) {
	name := f.Tag.String() + ".json"
	if strings.TrimSpace(f.Meta.Name) == "" {
		p.add("%s: _meta.name is empty", name)
	}
	if f.Meta.Dir != "ltr" && f.Meta.Dir != "rtl" {
		p.add("%s: _meta.dir must be ltr or rtl", name)
	}
	required := slices.Contains(requiredLocales, f.Tag)
	for _, k := range sortedKeys(base.Messages) {
		if _, ok := f.Messages[k]; !ok && required {
			p.add("%s: %s is missing", name, k)
		}
	}
	for _, k := range sortedKeys(f.Messages) {
		src := f.Messages[k]
		baseSrc, inBase := base.Messages[k]
		if !inBase {
			p.add("%s: %s is not in %s.json", name, k, i18n.BaseLocale)
			continue
		}
		if strings.TrimSpace(src) == "" {
			p.add("%s: %s is empty", name, k)
			continue
		}
		if strings.HasPrefix(src, placeholder) {
			p.add("%s: %s is still a placeholder: write the text", name, k)
		}
		m, err := i18n.ParseMessage(src)
		if err != nil {
			p.add("%s: %s: %v", name, k, err)
			continue
		}
		if err := m.CheckPlurals(f.Tag); err != nil {
			p.add("%s: %s: %v", name, k, err)
		}
		if f == base {
			continue
		}
		bm, err := i18n.ParseMessage(baseSrc)
		if err != nil {
			continue // reported for the base file
		}
		if got, want := m.Arguments(), bm.Arguments(); !sameMap(got, want) {
			p.add("%s: %s: arguments %v differ from %s %v", name, k, got, i18n.BaseLocale, want)
		}
		if got, want := m.SelectBranches(), bm.SelectBranches(); !sameMapFunc(got, want, slices.Equal[[]string]) {
			p.add("%s: %s: select branches %v differ from %s %v", name, k, got, i18n.BaseLocale, want)
		}
	}
	want, err := canonical(f, base)
	if err != nil {
		p.add("%s: %v", name, err)
		return
	}
	if got, err := os.ReadFile(filepath.Join(localesDir(root), name)); err != nil || !sameText(got, want) {
		p.add("%s is not in canonical form or its completeness is stale: run go run ./tools/i18n fix", name)
	}
}

// validKey checks the "module.page.meaning" form: at least three segments of
// lowercase letters, digits and underscores, each starting with a letter.
func validKey(k i18n.Key) error {
	segs := strings.Split(string(k), ".")
	if len(segs) < 3 {
		return errors.New("a key needs at least three segments, as in module.page.meaning")
	}
	for _, s := range segs {
		if s == "" || s[0] < 'a' || s[0] > 'z' || strings.Trim(s, "abcdefghijklmnopqrstuvwxyz0123456789_") != "" {
			return fmt.Errorf("segment %q must be lowercase letters, digits and underscores, starting with a letter", s)
		}
	}
	return nil
}

func sameMap[K comparable, V comparable](a, b map[K]V) bool {
	return sameMapFunc(a, b, func(x, y V) bool { return x == y })
}

func sameMapFunc[K comparable, V any](a, b map[K]V, eq func(V, V) bool) bool {
	if len(a) != len(b) {
		return false
	}
	for k, v := range a {
		w, ok := b[k]
		if !ok || !eq(v, w) {
			return false
		}
	}
	return true
}

type problems []string

func (p *problems) add(format string, a ...any) { *p = append(*p, fmt.Sprintf(format, a...)) }

func (p problems) err() error {
	if len(p) == 0 {
		return nil
	}
	for _, msg := range p {
		fmt.Fprintln(os.Stderr, msg)
	}
	return fmt.Errorf("%d problem(s)", len(p))
}
